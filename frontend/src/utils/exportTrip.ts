/**
 * Generates and downloads an executive-styled PDF Document (.pdf)
 */
export async function exportTripToPdf(plan: TripPlan): Promise<void> {
  const doc = new jsPDF({
    orientation: 'portrait',
    unit: 'mm',
    format: 'a4',
  });

  const pageWidth = doc.internal.pageSize.getWidth();
  const pageHeight = doc.internal.pageSize.getHeight();
  const margin = 14;
  const contentWidth = pageWidth - margin * 2;
  let cursorY = margin;

  // Function to ensure we don't overflow the page
  const checkPageBreak = (neededHeight: number) => {
    if (cursorY + neededHeight > pageHeight - margin - 10) {
      doc.addPage();
      cursorY = margin + 5;
    }
  };

  // 1. Top Decorative Brand Banner
  doc.setFillColor(15, 23, 42); // Slate 900
  doc.rect(margin, cursorY, contentWidth, 32, 'F');

  doc.setFont('helvetica', 'bold');
  doc.setFontSize(9);
  doc.setTextColor(245, 158, 11); // Amber 500
  doc.text('TRIPMAX • AI TRAVEL ARCHITECTURE', margin + 6, cursorY + 8);

  doc.setFontSize(18);
  doc.setTextColor(255, 255, 255);
  doc.text(plan.destination, margin + 6, cursorY + 18);

  doc.setFont('helvetica', 'normal');
  doc.setFontSize(9);
  doc.setTextColor(203, 213, 225); // Slate 300
  const tagline = doc.splitTextToSize(plan.tagline || `Curated ${plan.duration_days}-Day Journey`, contentWidth - 12);
  doc.text(tagline[0] || '', margin + 6, cursorY + 26);

  cursorY += 38;

  // 2. Summary Info Box
  doc.setFillColor(248, 250, 252); // Slate 50
  doc.setDrawColor(226, 232, 240); // Slate 200
  doc.rect(margin, cursorY, contentWidth, 20, 'FD');

  doc.setFont('helvetica', 'bold');
  doc.setFontSize(8);
  doc.setTextColor(100, 116, 139); // Slate 500
  doc.text('ORIGIN', margin + 4, cursorY + 6);
  doc.text('DURATION', margin + 44, cursorY + 6);
  doc.text('DATES', margin + 84, cursorY + 6);
  doc.text('TOTAL PROJECTED BUDGET', margin + 128, cursorY + 6);

  doc.setFontSize(9);
  doc.setTextColor(15, 23, 42); // Slate 900
  doc.text(plan.origin || 'Flexible', margin + 4, cursorY + 13);
  doc.text(`${plan.duration_days} Days`, margin + 44, cursorY + 13);
  doc.text(plan.dates || 'Upcoming Travel', margin + 84, cursorY + 13);

  doc.setTextColor(5, 150, 105); // Emerald 600
  doc.text(`${plan.budget.currency} ${plan.budget.total_estimated.toLocaleString()}`, margin + 128, cursorY + 13);

  cursorY += 26;

  // 3. Overview Paragraph
  checkPageBreak(30);
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(11);
  doc.setTextColor(15, 23, 42);
  doc.text('Executive Overview', margin, cursorY);
  cursorY += 5;

  doc.setFont('helvetica', 'normal');
  doc.setFontSize(8.5);
  doc.setTextColor(51, 65, 85);
  const overviewLines = doc.splitTextToSize(plan.overview || 'Comprehensive curated travel blueprint.', contentWidth);
  doc.text(overviewLines, margin, cursorY);
  cursorY += overviewLines.length * 4.2 + 4;

  if (plan.best_time_to_visit || plan.local_transport_pass_tip) {
    checkPageBreak(15);
    doc.setFont('helvetica', 'bold');
    doc.setFontSize(8.5);
    doc.setTextColor(15, 23, 42);
    if (plan.best_time_to_visit) {
      doc.text('Best Time to Visit: ', margin, cursorY);
      doc.setFont('helvetica', 'normal');
      doc.setTextColor(71, 85, 105);
      doc.text(plan.best_time_to_visit, margin + 28, cursorY);
      cursorY += 4.5;
    }
    if (plan.local_transport_pass_tip) {
      doc.setFont('helvetica', 'bold');
      doc.setTextColor(15, 23, 42);
      doc.text('Mobility & Passes: ', margin, cursorY);
      doc.setFont('helvetica', 'normal');
      doc.setTextColor(71, 85, 105);
      doc.text(plan.local_transport_pass_tip, margin + 28, cursorY);
      cursorY += 5.5;
    }
  }

  // 4. Budget Table
  checkPageBreak(50);
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(11);
  doc.setTextColor(15, 23, 42);
  doc.text('Budget Blueprint', margin, cursorY);
  cursorY += 2;

  const budgetBody = [
    ['Stays & Accommodations', `${plan.budget.currency} ${plan.budget.stay_cost.toLocaleString()}`],
    ['Transit & Intercity Travel', `${plan.budget.currency} ${plan.budget.transit_cost.toLocaleString()}`],
    ['Activities & Experiences', `${plan.budget.currency} ${plan.budget.activities_cost.toLocaleString()}`],
    ['Dining & Culinary', `${plan.budget.currency} ${plan.budget.food_dining_cost.toLocaleString()}`],
    ['Local Transport & Buffer', `${plan.budget.currency} ${plan.budget.buffer_local_transit_cost.toLocaleString()}`],
    ['Total Projected', `${plan.budget.currency} ${plan.budget.total_estimated.toLocaleString()}`],
  ];

  autoTable(doc, {
    startY: cursorY + 2,
    margin: { left: margin, right: margin },
    head: [['Category', 'Estimated Cost']],
    body: budgetBody,
    theme: 'grid',
    headStyles: { fillColor: [15, 23, 42], textColor: 255, fontSize: 8.5, fontStyle: 'bold' },
    bodyStyles: { fontSize: 8, textColor: [51, 65, 85] },
    alternateRowStyles: { fillColor: [248, 250, 252] },
  });

  cursorY = (doc as any).lastAutoTable.finalY + 8;

  // 5. Stays Table
  if (plan.stays && plan.stays.length > 0) {
    checkPageBreak(40);
    doc.setFont('helvetica', 'bold');
    doc.setFontSize(11);
    doc.setTextColor(15, 23, 42);
    doc.text('Curated Accommodations', margin, cursorY);

    const staysBody = plan.stays.map((s) => [
      s.name,
      s.neighborhood || 'Central',
      `${s.currency} ${s.price_per_night.toLocaleString()}/night`,
      `${s.currency} ${s.total_price.toLocaleString()}`,
      s.rating ? `${s.rating} ★` : 'Recommended',
    ]);

    autoTable(doc, {
      startY: cursorY + 3,
      margin: { left: margin, right: margin },
      head: [['Property', 'Neighborhood', 'Rate', 'Total', 'Rating']],
      body: staysBody,
      theme: 'grid',
      headStyles: { fillColor: [15, 23, 42], textColor: 255, fontSize: 8, fontStyle: 'bold' },
      bodyStyles: { fontSize: 7.5, textColor: [51, 65, 85] },
      alternateRowStyles: { fillColor: [248, 250, 252] },
    });

    cursorY = (doc as any).lastAutoTable.finalY + 8;
  }

  // 6. Day-by-day Itinerary
  checkPageBreak(40);
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(11);
  doc.setTextColor(15, 23, 42);
  doc.text('Day-by-Day Schedule', margin, cursorY);
  cursorY += 5;

  plan.itinerary.forEach((day) => {
    checkPageBreak(35);

    // Day Header Pill
    doc.setFillColor(241, 245, 249);
    doc.roundedRect(margin, cursorY, contentWidth, 7, 1.5, 1.5, 'F');
    doc.setFont('helvetica', 'bold');
    doc.setFontSize(9);
    doc.setTextColor(15, 23, 42);
    doc.text(`Day ${day.day}: ${day.title} ${day.theme ? `• ${day.theme}` : ''}`, margin + 3, cursorY + 4.8);
    cursorY += 10;

    // Slots
    const slots = [
      { label: 'Morning', val: `${day.morning.title} - ${day.morning.description}` },
      { label: 'Lunch', val: `${day.lunch_recommendation.place} (${day.lunch_recommendation.vibe || 'Local Eatery'}). Try: ${day.lunch_recommendation.dish}` },
      { label: 'Afternoon', val: `${day.afternoon.title} - ${day.afternoon.description}` },
      { label: 'Dinner', val: `${day.dinner_recommendation.place} (${day.dinner_recommendation.vibe || 'Local Dining'}). Try: ${day.dinner_recommendation.dish}` },
      { label: 'Evening', val: `${day.evening.title} - ${day.evening.description}` },
    ];

    slots.forEach((s) => {
      checkPageBreak(12);
      doc.setFont('helvetica', 'bold');
      doc.setFontSize(7.5);
      doc.setTextColor(180, 83, 9); // Amber 700
      doc.text(`${s.label}: `, margin + 3, cursorY);

      doc.setFont('helvetica', 'normal');
      doc.setTextColor(51, 65, 85);
      const lines = doc.splitTextToSize(s.val, contentWidth - 24);
      doc.text(lines, margin + 20, cursorY);
      cursorY += lines.length * 3.8 + 1.5;
    });

    if (day.transit_tips) {
      checkPageBreak(8);
      doc.setFont('helvetica', 'italic');
      doc.setFontSize(7);
      doc.setTextColor(100, 116, 139);
      doc.text(`Transit Note: ${day.transit_tips}`, margin + 3, cursorY);
      cursorY += 5;
    }

    cursorY += 3;
  });

  // Footer on all pages
  const totalPages = doc.getNumberOfPages();
  for (let i = 1; i <= totalPages; i++) {
    doc.setPage(i);
    doc.setFont('helvetica', 'normal');
    doc.setFontSize(7);
    doc.setTextColor(148, 163, 184); // Slate 400
    doc.text(
      `TripMax Travel Plan • ${plan.destination} • Page ${i} of ${totalPages}`,
      pageWidth / 2,
      pageHeight - 7,
      { align: 'center' }
    );
  }

  doc.save(cleanFilename(plan.destination, 'pdf'));
}
